export type IconName = keyof typeof ICONS;

type Props = {
  name: IconName;
  /** 1 ドットの大きさ（px、整数）。既定 2 */
  scale?: number;
  className?: string;
  /** "o" の点の色（既定は地の色） */
  fill?: string;
};

export function PixelIcon({ name, scale = 2, className, fill = "var(--c-panel)" }: Props) {
  const rows = ICONS[name];
  const w = rows[0].length;
  const h = rows.length;
  const rects: React.ReactElement[] = [];
  rows.forEach((row, y) => {
    // 横に続く点はまとめて1つの rect にする
    let x = 0;
    while (x < w) {
      const ch = row[x];
      if (ch === ".") {
        x++;
        continue;
      }
      let e = x + 1;
      while (e < w && row[e] === ch) e++;
      rects.push(<rect key={`${x},${y}`} x={x} y={y} width={e - x} height={1} fill={ch === "o" ? fill : "currentColor"} />);
      x = e;
    }
  });
  return (
    <svg className={`picon ${className ?? ""}`} width={w * scale} height={h * scale} viewBox={`0 0 ${w} ${h}`} aria-hidden="true">
      {rects}
    </svg>
  );
}
