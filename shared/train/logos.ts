// ロゴ（16×16、2色）の点のデータと、既製ロゴ12種。
// 点のデータは「1行を16ビット（左端が最上位）にして4桁の16進数、上の行から16行」の64文字（小文字）。

export const LOGO_SIZE = 16;

const LOGO_RE = /^[0-9a-f]{64}$/;

/** 正しい形式か（64文字の小文字の16進数） */
export function isLogoBits(bits: string): boolean {
  return LOGO_RE.test(bits);
}

/** (x, y) の点が描く色か */
export function logoBit(bits: string, x: number, y: number): boolean {
  const nibble = parseInt(bits[y * 4 + (x >> 2)], 16);
  return ((nibble >> (3 - (x & 3))) & 1) === 1;
}

/** 点のデータを 256 バイトの配列（1 が描く色）にする */
export function decodeLogo(bits: string): Uint8Array {
  const out = new Uint8Array(LOGO_SIZE * LOGO_SIZE);
  for (let i = 0; i < 64; i++) {
    const n = parseInt(bits[i], 16);
    for (let b = 0; b < 4; b++) out[i * 4 + b] = (n >> (3 - b)) & 1;
  }
  return out;
}

/** 256 バイトの配列（0 以外が描く色）を点のデータにする */
export function encodeLogo(pixels: ArrayLike<number>): string {
  if (pixels.length !== LOGO_SIZE * LOGO_SIZE) throw new Error("ロゴの点の数が違います");
  let s = "";
  for (let i = 0; i < 64; i++) {
    let n = 0;
    for (let b = 0; b < 4; b++) n = (n << 1) | (pixels[i * 4 + b] ? 1 : 0);
    s += n.toString(16);
  }
  return s;
}

/** 文字の絵（# が描く色、それ以外が地）を点のデータにする */
export function logoFromArt(rows: readonly string[]): string {
  if (rows.length !== LOGO_SIZE || rows.some((r) => r.length !== LOGO_SIZE)) throw new Error("ロゴの絵は16×16にしてください");
  const px = new Uint8Array(LOGO_SIZE * LOGO_SIZE);
  rows.forEach((r, y) => {
    for (let x = 0; x < LOGO_SIZE; x++) px[y * LOGO_SIZE + x] = r[x] === "#" ? 1 : 0;
  });
  return encodeLogo(px);
}

